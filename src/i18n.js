export const makeT = (lang) => (key, vars) => {
  if (typeof key !== "string") return key;
  let out = key;
  if (lang === "id") {
    if (key in ID) out = ID[key];
    else if (import.meta.env?.DEV) console.warn(`[i18n] missing id translation: "${key}"`);
  }
  return vars ? out.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : out;
};

// Decimal separator follows the language (57,1% in Indonesian, 57.1% in English).
export const makeFmt = (lang) => (value, digits = 1) =>
  Number(value).toLocaleString(lang === "id" ? "id-ID" : "en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits });

export const LangContext = createContext({ lang: "en", t: makeT("en"), fmt: makeFmt("en") });
export const useLang = () => useContext(LangContext);
